// Builds the command reference of docs/cli.html from the same command
// definitions `--help` prints, so the page and the program cannot disagree.
import type { CommandSpec, OptionSpecs } from '../../src/cli/command.ts';
import { exampleRoot } from '../../src/cli/commands/shared.ts';
import { commandSignature, optionLabel } from '../../src/cli/help.ts';
import { COMMANDS, GLOBAL_OPTIONS } from '../../src/cli/router.ts';

export const START = '<!-- generated by npm run docs:cli from src/cli; edit the commands, not this section -->';
export const END = '<!-- end of generated section -->';

export function escapeHtml(text: string): string {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
}

/** The id of a command's section, such as `command-site-add`. */
export function commandId(command: CommandSpec): string {
  return `command-${command.path.join('-')}`;
}

function optionTable(specs: OptionSpecs, caption: string): string[] {
  const rows = Object.entries(specs).map(
    ([name, spec]) => `      <tr><td><code>${escapeHtml(optionLabel(name, spec))}</code></td><td>${escapeHtml(spec.description)}</td></tr>`,
  );
  return [
    '  <table>',
    `    <caption>${escapeHtml(caption)}</caption>`,
    '    <thead><tr><th scope="col">Option</th><th scope="col">Does</th></tr></thead>',
    '    <tbody>',
    ...rows,
    '    </tbody>',
    '  </table>',
  ];
}

function commandSection(command: CommandSpec): string[] {
  const examples = command.examples.map((example) => escapeHtml(example.replaceAll('{root}', exampleRoot('linux'))));
  return [
    `<section class="command" id="${commandId(command)}">`,
    `  <h3><code>sync-servers ${escapeHtml(commandSignature(command))}</code></h3>`,
    `  <p>${escapeHtml(command.summary)}.</p>`,
    ...(command.options === undefined || Object.keys(command.options).length === 0 ? [] : optionTable(command.options, `Options of ${command.path.join(' ')}`)),
    ...(examples.length === 0 ? [] : ['  <pre><code>' + examples.join('\n') + '</code></pre>']),
    '</section>',
  ];
}

/** The generated part of docs/cli.html, markers included. */
export function commandReference(): string {
  const index = COMMANDS.map((command) => `  <li><a href="#${commandId(command)}"><code>${escapeHtml(command.path.join(' '))}</code></a>: ${escapeHtml(command.summary)}</li>`);
  return [
    START,
    '<ul class="command-index">',
    ...index,
    '</ul>',
    '<h3 id="global-options">Global options</h3>',
    '<p>Every command takes these.</p>',
    ...optionTable(GLOBAL_OPTIONS, 'Global options').map((line) => line.slice(2)),
    ...COMMANDS.flatMap(commandSection),
    END,
  ].join('\n');
}

/** `page` with its generated section replaced by `section`. */
export function replaceGenerated(page: string, section: string): string {
  const start = page.indexOf(START);
  const end = page.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('docs/cli.html has no generated section markers.');
  }
  return page.slice(0, start) + section + page.slice(end + END.length);
}
